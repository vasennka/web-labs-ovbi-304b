const orders = [
    { product: 'Ноутбук', price: 50000, quantity: 1 },
    { product: 'Мышь', price: 1500, quantity: 2 },
    { product: 'Клавиатура', price: 3000, quantity: 1 }
];

/**
 * Сумма корзины: price * quantity по каждой позиции.
 * reduce(колбэк, начальноеЗначение аккумулятора)
 */
const totalSum = orders.reduce((acc, order) => {
    return acc + order.price * order.quantity;
}, 0);

console.log('\n=== Задача 4. Агрегация (reduce) ===');
console.log('позиции и суммы:');
