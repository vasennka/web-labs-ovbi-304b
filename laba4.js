console.log('ожидание 56000 ->', totalSum === 56000 ? 'совпадает ✔' : 'не совпадает ✘');

// Бонус 1: reduce может вернуть не число, а ОБЪЕКТ — сгруппированный отчёт
const report = orders.reduce(
    (acc, order) => ({
        items: acc.items + order.quantity,
        sum: acc.sum + order.price * order.quantity,
        maxPosition: Math.max(acc.maxPosition, order.price * order.quantity)
    }),
    { items: 0, sum: 0, maxPosition: 0 }
);
console.log('отчёт одной операцией  =', report);

// Бонус 2: reduce как аналог map (квадраты)
console.log('reduce-аналог map      =', numbers.reduce((acc, n) => [...acc, n * n], []));

// Бонус 3: «ящик» товаров по первой букве — группировка
const grouped = orders.reduce((acc, order) => {
    const key = order.product[0];
    return { ...acc, [key]: [...(acc[key] ?? []), order.product] };
}, {});
console.log('группировка по буквам  =', grouped);

/* =========================================================================
 * ЗАДАЧА 5. Каррирование
 *   multiply(2)(3)    -> 6
 *   multiply(2)(3)(4) -> 24
 * ========================================================================= */

/**
 * Каррированная версия умножения: функция возвращает либо число (когда
 * аргументов достаточно), либо НОВУЮ функцию, которая «запомнила» уже
 * переданные множители (замыкание + rest-параметры).
 *
 * @param {...number} args — уже накопленные множители
 * @returns {number|Function}
 */
function multiply(...args) {
    const multiplyAll = (collected) => {
        // Возвращаемая функция помнит collected через замыкание
        return (...nextArgs) => {
            const all = [...collected, ...nextArgs];
            // Хитрость: функции в JS — объекты, им можно переопределить toString
            // (и Symbol.toPrimitive), чтобы console.log показывал число.
            const result = all.reduce((a, b) => a * b, 1);
            const fn = (...more) => multiplyAll(all)(...more);
            fn.toString = () => String(result);
            fn.valueOf = () => result;
            fn[Symbol.toPrimitive] = () => result;
            return fn;
        };
    };
    return multiplyAll([])(...args);
}

